#!/usr/bin/env python3
"""Generate Unicode 17 line-break tables from hash-pinned, unmodified UCD inputs.

Usage: python3 eng/generate-unicode-linebreak.py /path/to/ucd-17.0.0
The expected paths and hashes are recorded in Unicode17/linebreak-manifest.json.
"""
import hashlib
import json
from pathlib import Path
import sys

root = Path(__file__).resolve().parent.parent
source = Path(sys.argv[1])
fixture = root / 'tests/wordnet.Conversion.Tests/Fixtures/Unicode17'
manifest = json.loads((fixture / 'linebreak-manifest.json').read_text())
for name, expected in manifest['sha256'].items():
    if hashlib.sha256((source / name).read_bytes()).hexdigest() != expected:
        raise SystemExit('Unicode input hash mismatch: ' + name)


def ranges(path, select=lambda value: value):
    rows = []
    for raw in (source / path).read_text(encoding='utf-8').splitlines():
        line = raw.split('#')[0].strip()
        if not line:
            continue
        points, value = [part.strip() for part in line.split(';')[:2]]
        value = select(value)
        if value is None:
            continue
        ends = points.split('..'); first, last = int(ends[0], 16), int(ends[-1], 16)
        rows.append((first, last, value))
    rows.sort()
    result = []
    for first, last, value in rows:
        if result and first <= result[-1][1]:
            raise ValueError('Overlapping ranges in ' + path)
        if result and first == result[-1][1] + 1 and value == result[-1][2]:
            result[-1] = (result[-1][0], last, value)
        else:
            result.append((first, last, value))
    return result


tables = {
    'Break': ('XX', ranges('LineBreak.txt')),
    'Category': ('Other', ranges('extracted/DerivedGeneralCategory.txt', lambda value: value if value in ('Cn', 'Mc', 'Mn', 'Pf', 'Pi') else None)),
    'EastAsian': ('Other', ranges('EastAsianWidth.txt', lambda value: 'Wide' if value in ('F', 'W', 'H') else None)),
}
lines = ['// Generated by eng/generate-unicode-linebreak.py; Unicode 17.0.0, Unicode-3.0.',
         'namespace WordNet.Internal;', '', 'internal static class UnicodeLineBreakData', '{']
for name, (fallback, rows) in tables.items():
    names = [fallback] + sorted({value for _, _, value in rows} - {fallback})
    ids = {value: index for index, value in enumerate(names)}
    lines.append('    internal enum ' + name + ' { ' + ', '.join(names) + ' }')
    values = [str(value) for first, last, prop in rows for value in (first, last, ids[prop])]
    lines.append('    private static readonly int[] ' + name + 'Ranges = new int[]\n    {')
    for index in range(0, len(values), 24):
        lines.append('        ' + ', '.join(values[index:index + 24]) + ',')
    lines.append('    };')
    lines.append('    internal static ' + name + ' Get' + name + '(int scalar) => (' + name + ')Find(' + name + 'Ranges, scalar);')
lines += ['    private static int Find(int[] ranges, int scalar)', '    {',
          '        int left = 0, right = ranges.Length / 3 - 1;', '        while (left <= right)', '        {',
          '            int middle = left + (right - left) / 2, index = middle * 3;',
          '            if (scalar < ranges[index]) right = middle - 1;',
          '            else if (scalar > ranges[index + 1]) left = middle + 1;',
          '            else return ranges[index + 2];', '        }', '        return 0;', '    }', '}']
(root / 'src/wordnet/Internal/UnicodeLineBreakData.cs').write_text('\n'.join(lines) + '\n', encoding='utf-8')
(fixture / 'LineBreakTest.txt').write_bytes((source / 'auxiliary/LineBreakTest.txt').read_bytes())
