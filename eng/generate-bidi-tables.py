#!/usr/bin/env python3
"""Generate pinned Unicode 17 UAX #9 data; inputs never use runtime Unicode tables."""
from pathlib import Path
import hashlib
import json
import re
import sys

root = Path(__file__).resolve().parent.parent
source = Path(sys.argv[1])
fixture = root / 'tests/wordnet.Conversion.Tests/Fixtures/Unicode17'
manifest = json.loads((fixture / 'bidi-manifest.json').read_text())
for name, expected in manifest['sha256'].items():
    if hashlib.sha256((source / name).read_bytes()).hexdigest() != expected:
        raise SystemExit('Unicode bidi input hash mismatch: ' + name)

classes = ['L', 'R', 'AL', 'EN', 'ES', 'ET', 'AN', 'CS', 'NSM', 'BN', 'B', 'S', 'WS', 'ON',
           'LRE', 'LRO', 'RLE', 'RLO', 'PDF', 'LRI', 'RLI', 'FSI', 'PDI']
data = ['L'] * 0x110000
text = (source / 'DerivedBidiClass.txt').read_text()
aliases = {'Left_To_Right': 'L', 'Right_To_Left': 'R', 'Arabic_Letter': 'AL', 'European_Terminator': 'ET'}
for a, b, prop in re.findall(r'@missing: ([0-9A-F]+)\.\.([0-9A-F]+); (\w+)', text):
    start, end = int(a, 16), int(b, 16)
    data[start:end+1] = [aliases[prop]] * (end-start+1)
for raw in text.splitlines():
    line = raw.split('#')[0].strip()
    if not line:
        continue
    field, prop = [s.strip() for s in line.split(';')]
    bounds = field.split('..'); a, b = int(bounds[0], 16), int(bounds[-1], 16)
    data[a:b+1] = [prop] * (b-a+1)
ranges = []; start = 0
for end in range(1, len(data)+1):
    if end == len(data) or data[end] != data[start]:
        ranges.extend([start, end-1, classes.index(data[start])]); start = end

def records(name, bracket=False):
    rows = []
    for raw in (source / name).read_text().splitlines():
        line = raw.split('#')[0].strip()
        if not line:
            continue
        fields = [s.strip() for s in line.split(';')]
        rows.append((int(fields[0], 16), int(fields[1], 16), 1 if bracket and fields[2] == 'o' else 0))
    return sorted(rows)

lines = ['// Generated by eng/generate-bidi-tables.py; Unicode 17.0.0, Unicode-3.0.',
         'namespace WordNet.Internal;', '', 'internal static class UnicodeBidiData', '{',
         '    internal enum Kind { ' + ', '.join(classes) + ' }']
for name, values in [('Classes', ranges),
                     ('Brackets', [v for row in records('BidiBrackets.txt', True) for v in row]),
                     ('Mirrors', [v for row in records('BidiMirroring.txt') for v in row[:2]])]:
    lines.extend(['    internal static readonly int[] ' + name + ' = new int[]', '    {'])
    for i in range(0, len(values), 24):
        lines.append('        ' + ', '.join(map(str, values[i:i+24])) + ',')
    lines.append('    };')
lines += ['    internal static Kind Class(int scalar)', '    {',
          '        int lo = 0, hi = Classes.Length / 3 - 1;', '        while (lo <= hi)', '        {',
          '            int mid = lo + (hi - lo) / 2, p = mid * 3;',
          '            if (scalar < Classes[p]) hi = mid - 1; else if (scalar > Classes[p + 1]) lo = mid + 1; else return (Kind)Classes[p + 2];',
          '        }', '        return Kind.L;', '    }',
          '    internal static (int Pair, bool Open)? Bracket(int scalar)', '    {',
          '        int lo = 0, hi = Brackets.Length / 3 - 1;', '        while (lo <= hi)', '        {',
          '            int mid = lo + (hi - lo) / 2, p = mid * 3;',
          '            if (scalar < Brackets[p]) hi = mid - 1; else if (scalar > Brackets[p]) lo = mid + 1; else return (Brackets[p + 1], Brackets[p + 2] == 1);',
          '        }', '        return null;', '    }', '}']
(root / 'src/wordnet/Internal/UnicodeBidiData.cs').write_text('\n'.join(lines) + '\n')
for name in ['BidiCharacterTest.txt', 'BidiTest.txt']:
    (fixture / name).write_bytes((source / name).read_bytes())
