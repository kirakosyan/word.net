#!/usr/bin/env python3
"""Generate Unicode 17 boundary tables from unmodified UCD inputs (Unicode-3.0).

Usage: python3 eng/generate-unicode-tables.py /path/to/ucd-17.0.0
Inputs are pinned by tests/wordnet.Conversion.Tests/Fixtures/Unicode17/manifest.json.
Download paths relative to https://raw.githubusercontent.com/unicode-org/unicodetools/
main/unicodetools/data/ucd/17.0.0/ are listed in that manifest; hashes are mandatory.
This specification/data generator does not use runtime Unicode classifications.
"""
from pathlib import Path
import hashlib
import json
import sys

root = Path(__file__).resolve().parent.parent
source = Path(sys.argv[1])
fixture = root / 'tests/wordnet.Conversion.Tests/Fixtures/Unicode17'
manifest = json.loads((fixture / 'manifest.json').read_text())
for name, expected in manifest['sha256'].items():
    if hashlib.sha256((source / name).read_bytes()).hexdigest() != expected:
        raise SystemExit('Unicode input hash mismatch: ' + name)


def ranges(path, selector=None):
    result = []
    for raw in (source / path).read_text().splitlines():
        line = raw.split('#')[0].strip()
        if not line:
            continue
        parts = [p.strip() for p in line.split(';')]
        prop = selector(parts) if selector else parts[1]
        if prop is None:
            continue
        endpoints = parts[0].split('..')
        result.append((int(endpoints[0], 16), int(endpoints[-1], 16), prop))
    return sorted(result)


tables = {
    'Grapheme': ranges('auxiliary/GraphemeBreakProperty.txt'),
    'Word': ranges('auxiliary/WordBreakProperty.txt'),
    'Pictographic': ranges('emoji/emoji-data.txt', lambda p: 'Yes' if p[1] == 'Extended_Pictographic' else None),
    'Conjunct': ranges('DerivedCoreProperties.txt', lambda p: p[2] if p[1] == 'InCB' else None),
}
lines = ['// Generated by eng/generate-unicode-tables.py; Unicode 17.0.0, Unicode-3.0.',
         'namespace WordNet.Internal;', '', 'internal static class UnicodeBoundaryData', '{']
for name, rows in tables.items():
    names = ['Other'] + sorted({p for _, _, p in rows})
    ids = {p: i for i, p in enumerate(names)}
    lines.append('    internal enum ' + name + ' { ' + ', '.join(names) + ' }')
    values = [str(v) for a, b, p in rows for v in (a, b, ids[p])]
    lines.append('    private static readonly int[] ' + name + 'Ranges = new int[]\n    {')
    for index in range(0, len(values), 24):
        lines.append('        ' + ', '.join(values[index:index+24]) + ',')
    lines.append('    };')
    lines.append('    internal static ' + name + ' Get' + name + '(int scalar) => (' + name + ')Find(' + name + 'Ranges, scalar);')
lines += ['    private static int Find(int[] ranges, int scalar)', '    {',
          '        int left = 0, right = ranges.Length / 3 - 1;', '        while (left <= right)', '        {',
          '            int middle = left + (right - left) / 2, index = middle * 3;',
          '            if (scalar < ranges[index]) right = middle - 1;',
          '            else if (scalar > ranges[index + 1]) left = middle + 1;',
          '            else return ranges[index + 2];', '        }', '        return 0;', '    }', '}']
(root / 'src/wordnet/Internal/UnicodeBoundaryData.cs').write_text('\n'.join(lines) + '\n')
for name in ['GraphemeBreakTest.txt', 'WordBreakTest.txt']:
    (fixture / name).write_bytes((source / 'auxiliary' / name).read_bytes())
